    private async Task<Result<CommandResponse, SmartCardError>> ExecuteSelectIsd()
    {
        Result<SelectCommand, SmartCardError> selectCommandResult = SelectCommand.CreateForIssuerSecurityDomain();
        if (selectCommandResult.IsFailure)
            return Result.Failure<CommandResponse, SmartCardError>(selectCommandResult.Error);

        return await ExecuteCommand(selectCommandResult.Value);
    }

    private async Task<Result<CommandResponse, SmartCardError>> ExecuteInitializeUpdate(
        byte[] hostChallenge)
    {
        Result<InitializeUpdateCommand, SmartCardError> initCommandResult = InitializeUpdateCommand.Create(
                keyVersion: 0x00,
                keyIdentifier: 0x00,
                hostChallenge: hostChallenge);
        if (initCommandResult.IsFailure)
            return Result.Failure<CommandResponse, SmartCardError>(initCommandResult.Error);

        return await ExecuteCommand(initCommandResult.Value);
    }

    private async Task<Result<CommandResponse, SmartCardError>> ExecuteExternalAuthenticate(
        byte[] hostCryptogram)
    {
        // Calculate proper MAC according to GP specification instead of hardcoding zeros
        Result<SessionKeys, SmartCardError> sessionKeysResult = GetCurrentSessionKeys();

        return sessionKeysResult.Match(
            onSuccess: async sessionKeys =>
            {
                // Calculate proper C-MAC over EXTERNAL AUTHENTICATE command
                Result<byte[], SmartCardError> macResult = CalculateExternalAuthenticateMac(hostCryptogram, sessionKeys);

                return await macResult.Match(
                    onSuccess: async calculatedMac =>
                    {
                        TestContext.Out.WriteLine($"🔍 Using calculated MAC: {Convert.ToHexString(calculatedMac)}");
                        Result<ExternalAuthenticateCommand, SmartCardError> extAuthCommandResult = ExternalAuthenticateCommand.CreateWithMac(
                                securityLevel: SecurityLevel.CMac,
                                hostCryptogram: hostCryptogram,
                                mac: calculatedMac);
                        return await extAuthCommandResult.Match(
                            onSuccess: async command => await ExecuteCommand(command),
                            onFailure: error => Task.FromResult(Result.Failure<CommandResponse, SmartCardError>(error)));
                    },
                    onFailure: error =>
                    {
                        TestContext.Out.WriteLine($"❌ MAC calculation failed: {error}");
                        return Task.FromResult(Result.Failure<CommandResponse, SmartCardError>(error));
                    });
            },
            onFailure: async error =>
            {
                TestContext.Out.WriteLine($"❌ Failed to get session keys for MAC calculation: {error}");
                return Result.Failure<CommandResponse, SmartCardError>(
                    SmartCardError.CryptographicError("Session keys not available for MAC calculation"));
            }).GetAwaiter().GetResult();
    }

    private async Task<Result<CommandResponse, SmartCardError>> ExecuteCommand(
        IApduCommand command)
    {
        // Create pipeline processor with secure channel enabled
        CommandProcessing.CommandProcessor? processor = Pipeline.CommandProcessors.CreatePipeline(enableLogging: true, enableSecureChannel: true);

        // Get current environment and sync with virtual card secure channel state
        CommandProcessing.CommandEnvironment environment = CreatePipelineEnvironment();
        CommandProcessing.CommandEnvironment updatedEnvironment = (_transport as VirtualCardTransport)?.CreateUpdatedEnvironment(environment) ?? environment;

        SmartCardService service = new SmartCardService(updatedEnvironment, processor, _logger as ILogger<SmartCardService>);
        return await service.ExecuteCommandAsync(command, CancellationToken.None);
    }

    private byte[] GenerateHostChallenge()
    {
        // Use fixed deterministic host challenge so virtual card can consume entropy sequentially
        // This ensures host challenge (bytes 0-7) != card challenge (bytes 8-13) for proper SCP02 testing
        return [0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08];
    }

    private Result<SessionKeys, SmartCardError> DeriveSessionKeys(
        byte keyVersion, byte[] hostChallenge, byte[] cardChallenge)
    {
        // Get static keys from virtual card configuration
        return _virtualCard.Configuration.StaticKeys.TryGetValue(keyVersion, out IKeySet? keySet) && keySet is Scp02KeySet scp02KeySet
            ? DeriveSessionKeysFromScp02KeySet(scp02KeySet, hostChallenge, cardChallenge)
            : Result.Failure<SessionKeys, SmartCardError>(
                SmartCardError.CryptographicError("Failed to retrieve static keys for session derivation"));
    }

    private Result<SessionKeys, SmartCardError> DeriveSessionKeysFromScp02KeySet(
        Scp02KeySet scp02KeySet, byte[] hostChallenge, byte[] cardChallenge)
    {
        // ELIMINATE DRY VIOLATION: Use the same production KeyDerivationService that the virtual card uses
        // This ensures identical session key derivation logic between test and virtual card
        TestContext.Out.WriteLine($"🔍 Using production KeyDerivationService (same as virtual card)");
        TestContext.Out.WriteLine($"🔍 Host Challenge: {Convert.ToHexString(hostChallenge)} ({hostChallenge.Length} bytes)");
        TestContext.Out.WriteLine($"🔍 Card Challenge: {Convert.ToHexString(cardChallenge)} ({cardChallenge.Length} bytes)");
        TestContext.Out.WriteLine($"🔍 SCP Version: 0x02");

        // Use the same sequence counter as the virtual card (from INITIALIZE UPDATE response)
        byte[] sequenceCounter = [0x00, 0x01]; // Fixed sequence counter that virtual card uses

        // Create key derivation context exactly like virtual card does
        Result<KeyDerivationContext, SmartCardError> contextResult = KeyDerivationContext.CreateForScp02(
            scp02KeySet,
