    /// <summary>
    /// Gets the current session keys that were derived during INITIALIZE UPDATE.
    /// Required for calculating proper MAC on EXTERNAL AUTHENTICATE command.
    /// </summary>
    private Result<SessionKeys, SmartCardError> GetCurrentSessionKeys()
    {
        return _lastDerivedSessionKeys.Match(
            Some: sessionKeys =>
            {
                TestContext.Out.WriteLine($"✅ Session keys found: S-MAC = {Convert.ToHexString(sessionKeys.SMac[0..4])}...");
                return Result.Success<SessionKeys, SmartCardError>(sessionKeys);
            },
            None: () =>
            {
                TestContext.Out.WriteLine($"❌ No session keys available - _lastDerivedSessionKeys is None");
                return Result.Failure<SessionKeys, SmartCardError>(
                    SmartCardError.ConditionsNotSatisfied());
            });
    }

    /// <summary>
    /// Calculates the C-MAC for EXTERNAL AUTHENTICATE command according to GlobalPlatform Card Specification v2.3.1.
    /// Per GP Card Spec v2.3.1 Section E.3.2: "SCP02 mandates the use of a MAC on the EXTERNAL AUTHENTICATE command"
    /// and "For the EXTERNAL AUTHENTICATE command MAC verification, the ICV is set to zero."
    /// MAC is calculated over command header + host cryptogram using session-derived S-MAC key.
    /// </summary>
    private Result<byte[], SmartCardError> CalculateExternalAuthenticateMac(
        byte[] hostCryptogram, SessionKeys sessionKeys)
    {
        // Per GP Card Spec v2.3.1 Section E.3.2: Construct MAC input for EXTERNAL AUTHENTICATE command
        // EXTERNAL AUTHENTICATE command format: CLA=84 INS=82 P1=SecurityLevel P2=00 LC=10 Data=HostCryptogram
        byte[] commandHeader = [0x84, 0x82, (byte)SecurityLevel.CMac, 0x00, 0x10];
        byte[] macInput = commandHeader.Concat(hostCryptogram).ToArray();

        TestContext.Out.WriteLine($"🔍 GP Card Spec v2.3.1 Section E.3.2 - EXTERNAL AUTHENTICATE MAC Calculation:");
        TestContext.Out.WriteLine($"🔍 Command Header: {Convert.ToHexString(commandHeader)}");
        TestContext.Out.WriteLine($"🔍 Host Cryptogram: {Convert.ToHexString(hostCryptogram)}");
        TestContext.Out.WriteLine($"🔍 MAC Input (Header + Cryptogram): {Convert.ToHexString(macInput)}");
        TestContext.Out.WriteLine($"🔍 Session S-MAC Key: {Convert.ToHexString(sessionKeys.SMac)}");

        // FIXED: SCP02 uses 3DES MAC, not AES-CMAC per GP Card Spec v2.3.1 Section E.4.3
        return MacCalculations.CalculateScp02CommandMac(sessionKeys.SMac, macInput)
            .Map(calculatedMac =>
            {
                TestContext.Out.WriteLine($"🔍 SCP02 3DES MAC (8 bytes): {Convert.ToHexString(calculatedMac)}");
                return calculatedMac;
            });
    }

