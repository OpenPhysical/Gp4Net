    [SetUp]
    public void SetUp()
    {
        _logger = Microsoft.Extensions.Logging.Abstractions.NullLogger.Instance;

        // Create deterministic entropy for reproducible SCP02 tests
        // Host challenge: 01 02 03 04 05 06 07 08 (fixed in GenerateHostChallenge)
        // Card challenge: 09 0A 0B 0C 0D 0E (bytes 8-13, generated by virtual card)
        // Remaining: 0F 10 11... (bytes 14+, for other cryptographic operations)
        byte[] deterministicEntropy = Enumerable.Range(1, 64)
            .Select(i => (byte)i)
            .ToArray(); // Sequential values: 01, 02, 03, etc.

        // Create virtual card with entropy starting from position 8 (after host challenge)
        // This ensures card challenge will be 09 0A 0B 0C 0D 0E instead of 01 02 03 04 05 06
        byte[] virtualCardEntropy = deterministicEntropy.Skip(8).ToArray();

        _deterministicRng = PreloadedRngService.Create(deterministicEntropy)
            .Match(
                rng => rng,
                error => PreloadedRngService.Create([0x01]).GetValueOrDefault(null!)
            );

        // Create virtual card with entropy that starts at position 8
        _virtualCard = VirtualCardTestBuilder.P71CardWithEntropy(virtualCardEntropy)
            .Match(
                card => card,
                error => VirtualCardTestBuilder.P71Card()
            );

        _transport = new VirtualCardTransport(_virtualCard);
        _channel = new VirtualCardChannel(_virtualCard);
        _lastDerivedSessionKeys = Maybe<SessionKeys>.None; // Reset session keys
    }

