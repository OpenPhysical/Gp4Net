    private byte[] CalculateMac(byte[] key, byte[] data)
    {
        // Simplified MAC calculation using 3DES
        DesEdeEngine engine = new Org.BouncyCastle.Crypto.Engines.DesEdeEngine();
        byte[] expandedKey = key.Length == 16 ? key.Concat(key[..8]).ToArray() : key;

        engine.Init(true, new Org.BouncyCastle.Crypto.Parameters.KeyParameter(expandedKey));

        // Pad data to multiple of 16 bytes
        int paddedLength = ((data.Length + 15) / 16) * 16;
        byte[] paddedData = new byte[paddedLength];
        Array.Copy(data, paddedData, data.Length);

        // Process data in 16-byte blocks using functional approach
        return Enumerable.Range(0, paddedLength / 16)
            .Select(i => i * 16)
            .Aggregate(new byte[16], (mac, offset) =>
            {
                byte[] result = new byte[16];
                _ = engine.ProcessBlock(paddedData, offset, result, 0);
                return result;
            });
    }

    private byte[] CalculateAesCmac(byte[] key, byte[] data)
    {
        // Simplified AES-CMAC for SCP03
        AesEngine engine = new Org.BouncyCastle.Crypto.Engines.AesEngine();
        engine.Init(true, new Org.BouncyCastle.Crypto.Parameters.KeyParameter(key));

        // Pad data
        int paddedLength = ((data.Length + 15) / 16) * 16;
        byte[] paddedData = new byte[paddedLength];
        Array.Copy(data, paddedData, data.Length);
        if (data.Length < paddedLength)
        {
            paddedData[data.Length] = 0x80; // Padding
        }

        // Process blocks using functional approach
        return Enumerable.Range(0, paddedLength / 16)
            .Select(i => i * 16)
            .Aggregate(new byte[16], (cmac, offset) =>
            {
                // XOR block with current CMAC
                byte[] blockXorCmac = Enumerable.Range(0, 16)
                    .Select(j => (byte)(cmac[j] ^ paddedData[offset + j]))
                    .ToArray();

                byte[] result = new byte[16];
                _ = engine.ProcessBlock(blockXorCmac, 0, result, 0);
                return result;
            });
    }
