    /// <summary>
    /// Tests complete SCP02 secure channel establishment through GP pipeline.
    /// Verifies: SELECT → INITIALIZE UPDATE → EXTERNAL AUTHENTICATE → protected commands.
    /// </summary>
    [Test]
    public async Task SCP02_SecureChannel_EstablishmentThroughPipeline_ShouldSucceed()
    {
        // Arrange - Create pipeline environment with virtual card
        CommandProcessing.CommandEnvironment environment = CreatePipelineEnvironment();

        // Step 1: SELECT ISD - Required before secure channel establishment
        Result<CommandResponse, SmartCardError> selectResult = await ExecuteSelectIsd();

        selectResult.Match(
            onSuccess: result =>
            {
                _ = result.StatusWord.Should().Be(StatusWords.Success);
                _ = _virtualCard.IsSelected.Should().BeTrue("Card should be in selected state after SELECT");
            },
            onFailure: error =>
            {
                Assert.Fail($"SELECT ISD should succeed: {error}");
            });

        // Step 2: INITIALIZE UPDATE - Start secure channel establishment
        byte[] hostChallenge = GenerateHostChallenge();
        Result<CommandResponse, SmartCardError> initUpdateResult = await ExecuteInitializeUpdate(hostChallenge);

        byte[] initResponse = null;
        byte keyVersion = 0;
        byte scpId = 0;
        byte[] cardChallenge = null;
        byte[] cardCryptogram = null;
        byte[] sequenceCounter = null;

        initUpdateResult.Match(
            onSuccess: result =>
            {
                _ = result.StatusWord.Should().Be(StatusWords.Success);

                // Use proper InitializeUpdateResponse parser instead of raw array slicing
                Result<InitializeUpdateResponse, SmartCardError> parseResult = InitializeUpdateResponse.Parse(result.Data);
                parseResult.Match(
                    onSuccess: parsed =>
                    {
                        _ = parsed.ScpId.Should().Be((byte)0x02, "P71 cards use SCP02 protocol");
                        _ = parsed.KeyVersion.Should().BeOneOf([0x01, 0xFF], "Key version should be 01 or FF for P71");

                        initResponse = result.Data;
                        keyVersion = parsed.KeyVersion;
                        scpId = parsed.ScpId;
                        cardChallenge = parsed.CardChallenge; // This will be 6 bytes for SCP02
                        cardCryptogram = parsed.CardCryptogram;
                        sequenceCounter = parsed.SequenceCounter;
                    },
                    onFailure: parseError =>
                    {
                        Assert.Fail($"Failed to parse INITIALIZE UPDATE response: {parseError}");
                    });
            },
            onFailure: error =>
            {
                Assert.Fail($"INITIALIZE UPDATE should succeed: {error}");
            });

        // Step 3: Derive session keys using real cryptographic operations
        SessionKeys? sessionKeys = DeriveSessionKeys(keyVersion, hostChallenge, cardChallenge).Match(
            onSuccess: keys =>
            {
                // Store session keys for later use in EXTERNAL AUTHENTICATE
                _lastDerivedSessionKeys = Maybe<SessionKeys>.From(keys);
                return keys;
            },
            onFailure: error =>
            {
                Assert.Fail($"Session key derivation should succeed: {error}");
                return default;
            });

        // Step 4: Calculate host cryptogram and verify card cryptogram
        byte[]? hostCryptogram = CalculateAndVerifyCryptograms(
            sessionKeys, hostChallenge, cardChallenge, cardCryptogram, sequenceCounter).Match(
            onSuccess: crypto => crypto,
            onFailure: error =>
            {
                Assert.Fail($"Cryptogram calculation should succeed: {error}");
                return default;
            });

        // Step 5: EXTERNAL AUTHENTICATE - Complete secure channel establishment
        TestContext.Out.WriteLine($"🔍 Sending host cryptogram: {Convert.ToHexString(hostCryptogram)}");
        Result<CommandResponse, SmartCardError> extAuthResult = await ExecuteExternalAuthenticate(hostCryptogram);

        extAuthResult.Match(
            onSuccess: result =>
            {
                _ = result.StatusWord.Should().Be(StatusWords.Success);
                _ = _virtualCard.IsSecureChannelEstablished.Should().BeTrue("Secure channel should be established");
            },
            onFailure: error =>
            {
                TestContext.Out.WriteLine($"❌ EXTERNAL AUTHENTICATE failed with: {error}");
                Assert.Fail($"EXTERNAL AUTHENTICATE should succeed: {error}");
            });

        // Step 6: Verify protected commands work with established secure channel
        await VerifyProtectedCommandsWork();

        TestContext.Out.WriteLine("✅ SCP02 secure channel established successfully through pipeline");
    }

