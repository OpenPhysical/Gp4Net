    private byte[] CalculateMac(byte[] key, byte[] data)
    {
        // Simplified MAC calculation using 3DES
        DesEdeEngine engine = new DesEdeEngine();
        byte[] expandedKey = key.Length == 16 ? [.. key, .. key[..8]] : key;

        engine.Init(true, new KeyParameter(expandedKey));

        // Pad data to multiple of 16 bytes
        int paddedLength = (data.Length + 15) / 16 * 16;
        byte[] paddedData = new byte[paddedLength];
        Array.Copy(data, paddedData, data.Length);

        // Process data in 16-byte blocks
        return Enumerable
            .Range(0, paddedLength / 16)
            .Select(i => i * 16)
            .Aggregate(
                new byte[16],
                (mac, offset) =>
                {
                    byte[] result = new byte[16];
                    _ = engine.ProcessBlock(paddedData, offset, result, 0);
                    return result;
                }
            );
    }

