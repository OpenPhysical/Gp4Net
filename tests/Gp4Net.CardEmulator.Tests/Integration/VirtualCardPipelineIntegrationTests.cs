    {
        // Simplified 3DES key derivation for testing
        byte[] input = new byte[16];
        Array.Copy(derivationData, 0, input, 0, Math.Min(derivationData.Length, 15));
        input[15] = keyType;

        // Use BouncyCastle 3DES
        DesEdeEngine engine = new DesEdeEngine();
        byte[] expandedKey =
            staticKey.Length == 16 ? [.. staticKey, .. staticKey[..8]] : staticKey;

        engine.Init(true, new KeyParameter(expandedKey));

        byte[] output = new byte[16];
        _ = engine.ProcessBlock(input, 0, output, 0);
        _ = engine.ProcessBlock(input, 8, output, 8);

        return output;
    }

