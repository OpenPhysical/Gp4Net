    [SetUp]
    public void SetUp()
    {
        _logger = NullLogger.Instance;

        // Create deterministic entropy for reproducible SCP02 tests
        // Host challenge: 01 02 03 04 05 06 07 08 (fixed in GenerateHostChallenge)
        // Card challenge: 09 0A 0B 0C 0D 0E (bytes 8-13, generated by virtual card)
        // Remaining: 0F 10 11... (bytes 14+, for other cryptographic operations)
        byte[] deterministicEntropy = [.. Enumerable.Range(1, 64).Select(i => (byte)i)]; // Sequential values: 01, 02, 03, etc.

        // Create virtual card with entropy starting from position 8 (after host challenge)
        // This ensures card challenge will be 09 0A 0B 0C 0D 0E instead of 01 02 03 04 05 06
        byte[] virtualCardEntropy = [.. deterministicEntropy.Skip(8)];

        _deterministicRng = PreloadedRngService
            .Create(deterministicEntropy)
            .Match(rng => rng, error => PreloadedRngService.Create([0x01]).GetValueOrDefault());

        // Create virtual card with entropy that starts at position 8
        _virtualCard = VirtualCardTestBuilder
            .CreateWithEntropy(CardConfiguration.P71(), virtualCardEntropy)
            .Match(card => card, error => VirtualCardTestBuilder.CreateWithSecureRng(CardConfiguration.P71()));

        var transportResult = VirtualCardTransport.Create(_virtualCard);
        var channelResult = VirtualCardChannel.Create(_virtualCard);

        _transport = transportResult.GetValueOrDefault();
        _channel = channelResult.GetValueOrDefault();
    }

