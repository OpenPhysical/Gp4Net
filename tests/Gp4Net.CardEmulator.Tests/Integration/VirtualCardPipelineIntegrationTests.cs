    private async Task<Result<CommandResponse, SmartCardError>> ExecuteExternalAuthenticate(
        byte[] hostCryptogram
    )
    {
        // Calculate proper MAC according to GP specification instead of hardcoding zeros
        Result<SessionKeys, SmartCardError> sessionKeysResult = GetCurrentSessionKeys();

        return sessionKeysResult
            .Match(
                onSuccess: async sessionKeys =>
                {
                    // Calculate proper C-MAC over EXTERNAL AUTHENTICATE command
                    Result<byte[], SmartCardError> macResult = CalculateExternalAuthenticateMac(
                        hostCryptogram,
                        sessionKeys
                    );

                    return await macResult.Match(
                        onSuccess: async calculatedMac =>
                        {
                            TestContext.Out.WriteLine(
                                $"🔍 Using calculated MAC: {Convert.ToHexString(calculatedMac)}"
                            );
                            Result<
                                ExternalAuthenticateCommand,
