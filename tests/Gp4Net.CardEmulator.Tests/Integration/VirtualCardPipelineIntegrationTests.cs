    /// <summary>
    /// Establishes SCP02 secure channel and stores session keys for MAC calculations.
    /// Per GP Card Spec v2.3.1 Section 6.4.1.1: Complete SELECT → INITIALIZE UPDATE → EXTERNAL AUTHENTICATE sequence.
    /// </summary>
    private async Task<SessionKeys> EstablishSecureChannelScp02()
    {
        // Complete SCP02 secure channel establishment sequence
        Result<CommandResponse, SmartCardError> selectResult = await ExecuteSelectIsd();
        if (selectResult.IsFailure)
        {
            Assert.Fail($"SELECT ISD failed: {selectResult.Error}");
            return default!;
        }

        byte[] hostChallenge = GenerateHostChallenge();
        Result<CommandResponse, SmartCardError> initResult = await ExecuteInitializeUpdate(
            hostChallenge
        );

        if (initResult.IsSuccess)
        {
            CommandResponse? initResponse = initResult.Value;

            // Parse INITIALIZE UPDATE response using functional pattern
            Result<InitializeUpdateResponse, SmartCardError> parseResult =
                InitializeUpdateResponse.Parse(initResponse.Data);
            if (parseResult.IsSuccess)
            {
                InitializeUpdateResponse? response = parseResult.Value;

                // Derive session keys
                Result<SessionKeys, SmartCardError> sessionKeysResult = DeriveSessionKeys(
                    response.KeyVersion,
                    hostChallenge,
                    response.CardChallenge
                );
                if (sessionKeysResult.IsSuccess)
                {
                    SessionKeys? sessionKeys = sessionKeysResult.Value;

                    // Store session keys for MAC calculation during EXTERNAL AUTHENTICATE
                    _lastDerivedSessionKeys = Maybe<SessionKeys>.From(sessionKeys);
                    TestContext.Out.WriteLine(
                        $"✅ Session keys stored for EXTERNAL AUTHENTICATE: S-MAC = {Convert.ToHexString(sessionKeys.SMac[..4])}..."
                    );

                    // Calculate and verify cryptograms
                    Result<byte[], SmartCardError> hostCryptogramResult =
                        CalculateAndVerifyCryptograms(
                            sessionKeys,
                            hostChallenge,
                            response.CardChallenge,
                            response.CardCryptogram,
                            response.SequenceCounter
                        );

                    if (hostCryptogramResult.IsSuccess)
                    {
                        byte[]? hostCryptogram = hostCryptogramResult.Value;

                        // Execute EXTERNAL AUTHENTICATE with proper MAC
                        Result<CommandResponse, SmartCardError> extAuthResult =
                            await ExecuteExternalAuthenticate(hostCryptogram);
                        if (extAuthResult.IsSuccess)
                        {
                            TestContext.Out.WriteLine(
                                "✅ SCP02 secure channel established successfully"
                            );
                            return sessionKeys;
                        }
                        Assert.Fail($"EXTERNAL AUTHENTICATE failed: {extAuthResult.Error}");
                    }
                    else
                    {
                        Assert.Fail($"Cryptogram calculation failed: {hostCryptogramResult.Error}");
                    }
                }
                else
                {
                    Assert.Fail($"Session key derivation failed: {sessionKeysResult.Error}");
                }
            }
            else
            {
                Assert.Fail($"Failed to parse INITIALIZE UPDATE response: {parseResult.Error}");
            }
        }
        else
        {
            Assert.Fail($"INITIALIZE UPDATE failed: {initResult.Error}");
        }

        return default!;
    }

